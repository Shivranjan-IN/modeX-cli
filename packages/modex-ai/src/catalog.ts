import type { ModexModel } from "./types.js";

const VERIFIED_AT = "2026-10-01";

function free(
	overrides: Partial<ModexModel["freeMetadata"]> & { capabilities?: string[] } = {},
): ModexModel["freeMetadata"] {
	return {
		freeEligibility: "free",
		verifiedAt: VERIFIED_AT,
		verificationSource: "catalog",
		capabilities: overrides.capabilities ?? ["tool-calling"],
		quota: overrides.quota,
	};
}

function paid(verifiedAt: string): ModexModel["freeMetadata"] {
	return {
		freeEligibility: "paid",
		verifiedAt,
		verificationSource: "docs",
		capabilities: ["tool-calling"],
	};
}

